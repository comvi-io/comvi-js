// Renders scripts/icu-golden/cases.mjs with ICU4C and writes the golden fixture
// packages/core/tests/golden/icu4c.json. Maintainer tool: needs a C++ compiler and
// ICU4C (macOS: `brew install icu4c@78`); CI only READS the fixture.
//
//   node scripts/icu-golden/gen-icu4c.mjs [--icu /opt/homebrew/opt/icu4c@78]
//
// Dates render in UTC (TZ=UTC for the probe process).
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import url from "node:url";
import { expand } from "./cases.mjs";

const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
const OUT = path.join(ROOT, "packages/core/tests/golden/icu4c.json");
const icuFlag = process.argv.indexOf("--icu");
const ICU = icuFlag > 0 ? process.argv[icuFlag + 1] : "/opt/homebrew/opt/icu4c@78";

const rows = expand();
const cpp = (s) => JSON.stringify(s); // a JSON string literal is a valid C++ string literal for our ASCII+UTF-8 input

/**
 * A plain `{x}` prints `String(value)` in core, never through Intl (owner decision R3-17,
 * 28.10.2026), where ICU4C formats a number for the locale. So that ICU4C still renders
 * the rest of the row (`#`, selectors, quoting), each plain `{x}` holding a number is sent
 * to it as `{x__plain}` with the argument String(value); the fixture keeps the row's own
 * pattern and args and marks it `plain`.
 */
const PLAIN = /\{\s*([^\s,{}]+)\s*\}/g;
const plainOf = (row) => {
  const names = new Set();
  const pattern = row.pattern.replace(PLAIN, (all, name) => {
    if (typeof row.args[name] !== "number") return all;
    names.add(name);
    return `{${name}__plain}`;
  });
  return { pattern, names };
};

const calls = rows.map((row, i) => {
  const plain = plainOf(row);
  const args = { ...row.args };
  for (const k of plain.names) args[`${k}__plain`] = String(row.args[k]);
  const names = Object.keys(args);
  const vals = names.map((k) => {
    const v = args[k];
    if (k.endsWith("__plain")) return `Formattable(UnicodeString::fromUTF8(${cpp(v)}))`;
    if (typeof v === "number") return `Formattable((double)${v})`;
    // A `coerce` row passes a numeric string the way core reads it: Number(string).
    if (typeof v === "string" && row.coerce) return `Formattable((double)${Number(v)})`;
    if (typeof v === "string") return `Formattable(UnicodeString::fromUTF8(${cpp(v)}))`;
    return `Formattable((UDate)${v.$date}.0, Formattable::kIsDate)`;
  });
  return `  { UnicodeString n[] = {${names.map((k) => `UnicodeString::fromUTF8(${cpp(k)})`).join(", ") || "UnicodeString()"}};
    Formattable a[] = {${vals.join(", ") || "Formattable()"}};
    run(${i}, ${cpp(row.locale)}, ${cpp(plain.pattern)}, n, a, ${names.length}); }`;
});

const source = `#include <unicode/msgfmt.h>
#include <unicode/locid.h>
#include <unicode/uversion.h>
#include <iostream>
using namespace icu;
static void run(int id, const char* loc, const char* pat, const UnicodeString* names, const Formattable* args, int count) {
  UErrorCode st = U_ZERO_ERROR;
  MessageFormat mf(UnicodeString::fromUTF8(pat), Locale::forLanguageTag(loc, st), st);
  UnicodeString out;
  if (U_SUCCESS(st)) mf.format(names, args, count, out, st);
  std::string s; out.toUTF8String(s);
  std::cout << id << "\\t" << (U_FAILURE(st) ? std::string("ERR:") + u_errorName(st) : s) << "\\n";
}
int main() {
  std::cout << "version\\t" << U_ICU_VERSION << "\\n";
${calls.join("\n")}
}
`;

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "comvi-icu4c-"));
const src = path.join(dir, "golden.cpp");
const bin = path.join(dir, "golden");
fs.writeFileSync(src, source);
const cc = spawnSync(
  "clang++",
  ["-std=c++17", `-I${ICU}/include`, src, `-L${ICU}/lib`, "-licuuc", "-licui18n", "-o", bin],
  { encoding: "utf8" },
);
if (cc.status !== 0) throw new Error(`clang++ failed:\n${cc.stderr}`);
const run = spawnSync(bin, [], {
  encoding: "utf8",
  env: {
    ...process.env,
    TZ: "UTC",
    DYLD_LIBRARY_PATH: `${ICU}/lib`,
    LD_LIBRARY_PATH: `${ICU}/lib`,
  },
});
if (run.status !== 0) throw new Error(`probe failed:\n${run.stderr}`);
fs.rmSync(src);
fs.rmSync(bin);
fs.rmdirSync(dir);

let version;
const results = new Map();
for (const line of run.stdout.split("\n")) {
  if (!line) continue;
  const tab = line.indexOf("\t");
  const id = line.slice(0, tab);
  const value = line.slice(tab + 1);
  if (id === "version") version = value;
  else results.set(Number(id), value);
}

const fixture = {
  note: "Generated by scripts/icu-golden/gen-icu4c.mjs from scripts/icu-golden/cases.mjs. Do not edit by hand.",
  reference: `ICU4C ${version} MessageFormat (ApostropheMode DOUBLE_OPTIONAL), TZ=UTC`,
  rows: rows.map((row, i) => {
    const out = results.get(i);
    if (out === undefined) throw new Error(`no result for row ${i}`);
    const failed = out.startsWith("ERR:");
    if (failed !== row.error) {
      throw new Error(
        `row ${i} ${JSON.stringify(row.pattern)} [${row.locale}]: cases.mjs says error=${row.error}, ICU4C says ${out}`,
      );
    }
    if (failed)
      return { pattern: row.pattern, locale: row.locale, args: row.args, error: out.slice(4) };
    const ok = { pattern: row.pattern, locale: row.locale, args: row.args, expected: out };
    if (plainOf(row).names.size) ok.plain = true;
    return row.coerce ? { ...ok, coerced: true } : ok;
  }),
};
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(fixture, null, 2) + "\n");
console.log(`${fixture.reference}: ${fixture.rows.length} rows -> ${path.relative(ROOT, OUT)}`);
