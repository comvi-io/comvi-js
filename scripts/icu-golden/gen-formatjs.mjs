// Renders the S3 differential subset (lot 0, spike S3: `diff.mjs`) that falls inside
// the grammar @comvi/core 0.8 implements — plural / selectordinal / select / =N /
// offset: / `#`, no number/date/time arguments — with intl-messageformat, and writes
// packages/core/tests/golden/formatjs.json. Maintainer tool; CI only READS the fixture.
//
//   npm install --prefix <tmp> intl-messageformat@10.7.16
//   node scripts/icu-golden/gen-formatjs.mjs <tmp>/node_modules/intl-messageformat
//
// Plain `{x}` with a NUMBER is deliberately absent: intl-messageformat prints it with
// String(), ICU4C (the golden reference, gen-icu4c.mjs) formats it for the locale,
// and core follows ICU4C.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { createRequire } from "node:module";

const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
const OUT = path.join(ROOT, "packages/core/tests/golden/formatjs.json");
const modPath = process.argv[2];
if (!modPath) throw new Error("usage: gen-formatjs.mjs <path to node_modules/intl-messageformat>");
const require = createRequire(path.join(path.resolve(modPath), "package.json"));
const { IntlMessageFormat } = require(path.resolve(modPath));
const version = JSON.parse(fs.readFileSync(path.join(modPath, "package.json"), "utf8")).version;

export const LOCALES = ["en", "de", "uk", "ar-EG", "ja"];
export const SUBSET = [
  ["{n, plural, one {# item} other {# items}}", [{ n: 1 }, { n: 5 }, { n: 1234567.5 }, { n: 21 }]],
  [
    "{n, plural, offset:1 =0 {nobody} =1 {only {who}} one {{who} and # other} other {{who} and # others}}",
    [
      { n: 0, who: "Ann" },
      { n: 1, who: "Ann" },
      { n: 2, who: "Ann" },
      { n: 6, who: "Ann" },
      { n: 23, who: "Ann" },
    ],
  ],
  [
    "{g, select, female {{n, plural, one {She has # item} other {She has # items}}} other {{n, plural, =0 {They have none} one {They have # item} other {They have # items}}}}",
    [
      { g: "female", n: 1 },
      { g: "female", n: 3 },
      { g: "x", n: 0 },
      { g: "x", n: 2000 },
    ],
  ],
  [
    "{n, selectordinal, one {#st} two {#nd} few {#rd} other {#th}}",
    [{ n: 1 }, { n: 2 }, { n: 3 }, { n: 11 }, { n: 103 }],
  ],
  [
    "{a, plural, other {{b, select, x {{c, plural, one {# c} other {# cs}}} other {#}}}}",
    [
      { a: 7, b: "x", c: 1 },
      { a: 7, b: "y", c: 1 },
    ],
  ],
  [
    "{g, select, female {She} male {He} other {They}}",
    [{ g: "female" }, { g: "male" }, { g: "x" }],
  ],
  [
    "{n, plural, =0 {none} =1 {exactly one} other {# left}}",
    [{ n: 0 }, { n: 1 }, { n: 42 }, { n: 1000 }],
  ],
  [
    "{n, plural, other {{g, select, female {she has # items} other {they have # items}}}}",
    [{ n: 3, g: "female" }],
  ],
  [
    "{who} has {n, plural, one {# cat} other {# cats}}",
    [
      { who: "Ann", n: 1 },
      { who: "Bo", n: 12 },
    ],
  ],
];

const rows = [];
for (const [pattern, argSets] of SUBSET)
  for (const locale of LOCALES)
    for (const args of argSets) {
      const expected = new IntlMessageFormat(pattern, locale).format(args);
      rows.push({ pattern, locale, args, expected });
    }

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  JSON.stringify(
    {
      note: "Generated by scripts/icu-golden/gen-formatjs.mjs (the supported-grammar subset of lot-0 S3 diff.mjs). Do not edit by hand.",
      reference: `intl-messageformat ${version}`,
      rows,
    },
    null,
    2,
  ) + "\n",
);
console.log(`intl-messageformat ${version}: ${rows.length} rows -> ${path.relative(ROOT, OUT)}`);
