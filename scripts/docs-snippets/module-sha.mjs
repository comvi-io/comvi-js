/**
 * Parity marker for the docs snippet gate (lot D2a).
 *
 * The module lives here, in js-sdk, next to the packages and the tooling it
 * reasons about. The www site is a different repository and needs the same
 * rules, so it carries a COPY (docs-0.5 plan §7.3 — publishing the module or
 * wiring a submodule is deferred to D2b). A copy with no check is a copy that
 * drifts, which is the exact failure this whole lot exists to stop.
 *
 * The two sides pin the hash differently, and the asymmetry is the point:
 *
 *   - js-sdk hashes its files and compares against the `MODULE_SHA` marker
 *     beside them (`run.test.mjs`). The marker is regenerated here, on purpose,
 *     whenever the module changes.
 *   - www pins the hash as a LITERAL inside its parity spec, and that spec is
 *     NOT one of the copied files. A marker file would have travelled with the
 *     copy along with the `--write` that regenerates it, so a diverged copy
 *     could re-bless itself and stay green. A literal in a file the copy does
 *     not contain cannot be regenerated by copying — only by a person who read
 *     the diff.
 *
 * Updating the copy is therefore deliberate: change the module here, run
 * `node scripts/docs-snippets/module-sha.mjs --write`, copy the hashed files
 * and the `fixtures/` tree across, and paste the printed sha into www's parity
 * spec.
 *
 * `fixtures/` is hashed as a TREE, file by file in sorted order, because it is
 * as much of the gate as the code is: the same page compiles differently
 * against a different `src/i18n.ts`, and a copy that took the code without the
 * fixtures would produce a different verdict while reporting a matching module.
 * `link-sdk.mjs` is deliberately NOT hashed — www installs `@comvi/*` from npm
 * and has no workspace to pack.
 */

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Hashed in this order; the marker file itself is not part of the hash. */
export const MODULE_FILES = [
  "extract.mjs",
  "lint.mjs",
  // `surface.mjs` is hashed even though it is INERT in the www copy (no
  // `packages/` tree there, so `loadRepoSurface` returns null and
  // `banned/unresolved-comvi-import` reports nothing). `lint.mjs` imports it
  // unconditionally, so a copy that took the lint without it does not load at
  // all — and a copy that took a STALE one would answer a different surface the
  // day www is pointed at installed packages. Hashing it is what makes both
  // failures a marker mismatch instead of a surprise.
  "surface.mjs",
  "project.mjs",
  "typecheck.mjs",
  "sfc-check.mjs",
  "run.mjs",
  "module-sha.mjs",
];

/** Hashed as a tree, after the files above. */
export const MODULE_DIRS = ["fixtures"];

export const MARKER_FILE = "MODULE_SHA";

/** Every file under `dir`, as POSIX paths relative to it, sorted. */
function walk(dir, prefix = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out.sort();
}

export function computeModuleSha(dir) {
  const hash = createHash("sha256");
  for (const name of MODULE_FILES) {
    hash.update(name);
    hash.update("\0");
    hash.update(fs.readFileSync(path.join(dir, name)));
    hash.update("\0");
  }
  for (const treeName of MODULE_DIRS) {
    const treeDir = path.join(dir, treeName);
    if (!fs.existsSync(treeDir)) continue;
    for (const rel of walk(treeDir)) {
      hash.update(`${treeName}/${rel}`);
      hash.update("\0");
      hash.update(fs.readFileSync(path.join(treeDir, rel)));
      hash.update("\0");
    }
  }
  return hash.digest("hex");
}

/** The `SNIPPETS_MODULE_SHA` recorded in the marker, or `null` when absent. */
export function readMarker(dir) {
  const file = path.join(dir, MARKER_FILE);
  if (!fs.existsSync(file)) return null;
  return fs.readFileSync(file, "utf8").match(/^SNIPPETS_MODULE_SHA=([0-9a-f]{64})$/m)?.[1] ?? null;
}

export function writeMarker(dir) {
  const sha = computeModuleSha(dir);
  const body =
    "# Parity marker for scripts/docs-snippets — see module-sha.mjs.\n" +
    "# Regenerate with: node scripts/docs-snippets/module-sha.mjs --write\n" +
    `SNIPPETS_MODULE_SHA=${sha}\n`;
  fs.writeFileSync(path.join(dir, MARKER_FILE), body);
  return sha;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = path.dirname(fileURLToPath(import.meta.url));
  if (process.argv.includes("--write")) {
    const sha = writeMarker(dir);
    console.log(`docs-snippets: SNIPPETS_MODULE_SHA=${sha}`);
    console.log(
      `docs-snippets: pin this in www's parity spec: const EXPECTED_MODULE_SHA = '${sha}';`,
    );
  } else {
    console.log(computeModuleSha(dir));
  }
}
