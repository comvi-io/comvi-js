/**
 * The declaration format lives in `@comvi/typegen`, shared with `@comvi/cli`.
 * This module only supplies the plugin's own header line, so a project that
 * generates types with the CLI in CI and with this plugin in dev cannot see the
 * two disagree.
 */

import {
  emitDeclarations as emitShared,
  type EmitOptions as SharedEmitOptions,
  type ProjectSchema,
} from "@comvi/typegen";

/** The plugin owns the header line, so the caller does not choose it. */
export type EmitOptions = Omit<SharedEmitOptions, "generatedBy">;

export function emitDeclarations(schema: ProjectSchema, options: EmitOptions = {}): string {
  return emitShared(schema, {
    ...options,
    // Header line 3 of every declarations file this plugin writes. Spelled here
    // rather than in a module constant: a constant is read once at import,
    // before any test can observe it changing.
    generatedBy: "DO NOT EDIT — regenerated by @comvi/vite-plugin on every file change",
  });
}
