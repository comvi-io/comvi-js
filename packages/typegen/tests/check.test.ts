import { describe, it, expect } from "vitest";
import { countKeyLines, emitDeclarations, normalizeGenerated } from "../src/index";
import type { ProjectSchema } from "../src/index";

const SCHEMA: ProjectSchema = {
  keys: {
    "common:greeting": { params: [{ name: "name", type: "string" }] },
    "common:welcome": { params: [] },
  },
};

const CLI_GENERATED_BY = "DO NOT EDIT MANUALLY - This file is generated by @comvi/cli";

/**
 * What `@comvi/cli` 0.4 wrote to disk: today's output, its own name on header
 * line 3, plus the `Generated at:` line the emitter used to stamp under it.
 */
function generatedByV04(schema: ProjectSchema): string {
  const lines = withHeaderNotice(schema, CLI_GENERATED_BY).split("\n");
  lines.splice(3, 0, " * Generated at: 2026-01-01T00:00:00.000Z");
  return lines.join("\n");
}

/** Header line 3 as the CLI and the Vite plugin each used to stamp it. */
const LEGACY_NOTICES = [
  "DO NOT EDIT MANUALLY - This file is generated by @comvi/cli",
  "DO NOT EDIT \u2014 regenerated by @comvi/vite-plugin on every file change",
];

/** Today's output with header line 3 replaced, i.e. a file an older tool left. */
function withHeaderNotice(schema: ProjectSchema, notice: string): string {
  const lines = emitDeclarations(schema).split("\n");
  lines[2] = ` * ${notice}`;
  return lines.join("\n");
}

describe("countKeyLines", () => {
  it("counts the JSON-quoted key lines this emitter writes", () => {
    expect(countKeyLines(emitDeclarations(SCHEMA))).toBe(2);
  });

  it("counts the single-quoted key lines an older generator left behind", () => {
    const legacy = [
      "  interface TranslationKeys {",
      "    'common:hello': never;",
      "    'a': never;",
      "  }",
    ];

    expect(countKeyLines(legacy.join("\n"))).toBe(2);
  });

  it("counts a key whose quoted name contains an escaped quote", () => {
    expect(countKeyLines('    "say \\"hi\\"": never;\n')).toBe(1);
  });

  it("does not count a declaration-shaped line that starts at column zero", () => {
    expect(countKeyLines('/** header */\n"foo": never;\n')).toBe(0);
    expect(countKeyLines('"foo": never;\n')).toBe(0);
  });

  it("does not count a quoted colon that merely appears inside a string", () => {
    expect(countKeyLines("    const shape = \"quoted 'fake': entry;\";\n")).toBe(0);
  });

  it("counts nothing in a file with no key lines", () => {
    expect(countKeyLines("export {};\n")).toBe(0);
  });
});

describe("normalizeGenerated", () => {
  it("equates a file written by 0.4 with the output this emitter produces now", () => {
    const current = withHeaderNotice(SCHEMA, CLI_GENERATED_BY);

    expect(normalizeGenerated(generatedByV04(SCHEMA))).toBe(normalizeGenerated(current));
  });

  it("equates files whose header line carries either tool's old wording", () => {
    // 0.4/early-0.5 stamped the generating tool on header line 3. One neutral
    // line is the contract now, so a file left by either tool must normalize to
    // today's output or `--check` reports drift a regeneration cannot clear.
    const current = normalizeGenerated(emitDeclarations(SCHEMA));

    for (const notice of LEGACY_NOTICES) {
      expect(normalizeGenerated(withHeaderNotice(SCHEMA, notice))).toBe(current);
    }
  });

  it("removes the whole timestamp line, not just its tail", () => {
    expect(normalizeGenerated(generatedByV04(SCHEMA))).not.toContain(" * \n");
  });

  it("leaves a file that carries no timestamp line untouched apart from trimming", () => {
    expect(normalizeGenerated("first\nsecond")).toBe("first\nsecond");
  });

  it("ignores trailing whitespace", () => {
    const current = withHeaderNotice(SCHEMA, CLI_GENERATED_BY);

    expect(normalizeGenerated(`${current}\n\n  `)).toBe(normalizeGenerated(current));
  });

  it("keeps a declaration line whose own key contains the timestamp text", () => {
    // Only the header comment is dropped. Matching the marker anywhere on a
    // line would erase a real key from both sides of the comparison, hiding
    // drift in it forever.
    const noon: ProjectSchema = { keys: { "admin:Generated at: noon": { params: [] } } };
    const dusk: ProjectSchema = { keys: { "admin:Generated at: dusk": { params: [] } } };

    expect(normalizeGenerated(emitDeclarations(noon))).toContain("admin:Generated at: noon");
    expect(normalizeGenerated(emitDeclarations(noon))).not.toBe(
      normalizeGenerated(emitDeclarations(dusk)),
    );
  });

  it("keeps two files apart when a real declaration line differs", () => {
    const other: ProjectSchema = { keys: { "common:welcome": { params: [] } } };

    expect(normalizeGenerated(generatedByV04(SCHEMA))).not.toBe(
      normalizeGenerated(withHeaderNotice(other, CLI_GENERATED_BY)),
    );
  });
});
