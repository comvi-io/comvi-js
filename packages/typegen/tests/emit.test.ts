import { describe, it, expect } from "vitest";
import ts from "typescript";
import { emitDeclarations } from "../src/index";
import type { ProjectSchema } from "../src/index";

/** Syntax errors in the emitted declarations, as TypeScript reports them. */
function syntacticDiagnosticsOf(source: string): string[] {
  const { diagnostics = [] } = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: { module: ts.ModuleKind.ESNext },
  });

  return diagnostics.map((diagnostic) =>
    ts.flattenDiagnosticMessageText(diagnostic.messageText, " "),
  );
}

/** The emitted `TranslationKeys` member lines, in emitted order, without indentation. */
function keyLinesOf(output: string): string[] {
  return (output.match(/^ {4}\S.*$/gm) ?? []).map((line) => line.trim());
}

/**
 * Keys that a naive emitter gets wrong: an apostrophe closes a single-quoted
 * property, a hyphen cannot be a bare param name, and the `Zed`/`apple` pair
 * orders one way by code unit and the other by `localeCompare`.
 *
 * This fixture arrived from `scripts/typegen-emitters-parity.test.mjs`, which
 * compared the two emitter copies `@comvi/cli` and `@comvi/vite-plugin` used to
 * ship. There is one copy now, so the fixture pins its output instead.
 */
const SCHEMA: ProjectSchema = {
  keys: {
    "admin:Zed": { params: [] },
    "admin:apple": { params: [] },
    "admin:a-b": { params: [] },
    "admin:ab": { params: [] },
    "admin:errors.it's": { params: [] },
    "admin:ключ": { params: [] },
    "admin:greeting": { params: [{ name: "user-name", type: "string" }] },
  },
};

describe("emitDeclarations", () => {
  it("quotes every key and param name as JSON, in code-unit order", () => {
    expect(keyLinesOf(emitDeclarations(SCHEMA))).toEqual([
      '"admin:Zed": never;',
      '"admin:a-b": never;',
      '"admin:ab": never;',
      '"admin:apple": never;',
      '"admin:errors.it\'s": never;',
      '"admin:greeting": { "user-name": string };',
      '"admin:ключ": never;',
    ]);
  });

  it("emits a syntactically valid declaration file for that fixture", () => {
    expect(syntacticDiagnosticsOf(emitDeclarations(SCHEMA))).toEqual([]);
  });

  it("emits the whole file, header and module augmentation included", () => {
    const schema: ProjectSchema = {
      keys: {
        "common:welcome": { params: [] },
        "common:greeting": { params: [{ name: "name", type: "string" }] },
        "common:items": { params: [{ name: "count", type: "number" }] },
        "admin:dashboard": { params: [] },
      },
    };

    expect(emitDeclarations(schema, { generatedBy: "DO NOT EDIT — generated by the test" })).toBe(
      [
        "/**",
        " * Auto-generated translation keys",
        " * DO NOT EDIT — generated by the test",
        " */",
        "",
        "// Import to ensure module is resolved before augmentation",
        "import '@comvi/core';",
        "",
        "declare module '@comvi/core' {",
        "  interface TranslationKeys {",
        '    "admin:dashboard": never;',
        '    "common:greeting": { "name": string };',
        '    "common:items": { "count": number };',
        '    "common:welcome": never;',
        "  }",
        "}",
        "",
        "export {};",
        "",
      ].join("\n"),
    );
  });

  it("never stamps a timestamp into the output", () => {
    const first = emitDeclarations(SCHEMA);
    const second = emitDeclarations(SCHEMA);

    expect(first).not.toContain("Generated at:");
    expect(first).toBe(second);
  });

  it("puts generatedBy on header line 3", () => {
    const result = emitDeclarations(SCHEMA, {
      generatedBy: "DO NOT EDIT MANUALLY - This file is generated by @comvi/cli",
    });

    expect(result.split("\n")[2]).toBe(
      " * DO NOT EDIT MANUALLY - This file is generated by @comvi/cli",
    );
  });

  it("falls back to a tool-neutral header line when generatedBy is omitted", () => {
    expect(emitDeclarations(SCHEMA).split("\n")[2]).toBe(
      " * DO NOT EDIT — this file is generated from your translation schema",
    );
  });

  it("emits the empty skeleton for a schema with no keys", () => {
    const result = emitDeclarations({ keys: {} });

    expect(keyLinesOf(result)).toEqual([]);
    expect(result).toContain("  interface TranslationKeys {\n  }");
    expect(result).toContain("export {};");
  });

  it("strips the conventional default namespace when none is configured", () => {
    const schema: ProjectSchema = {
      keys: {
        "default:title": { params: [] },
        "admin:title": { params: [] },
      },
    };

    expect(keyLinesOf(emitDeclarations(schema))).toEqual([
      '"admin:title": never;',
      '"title": never;',
    ]);
  });

  it("strips a configured default namespace and leaves every other prefix", () => {
    const schema: ProjectSchema = {
      keys: {
        "common:hello": { params: [] },
        "auth:login": { params: [] },
        "default:kept": { params: [] },
      },
    };

    expect(keyLinesOf(emitDeclarations(schema, { defaultNs: "common" }))).toEqual([
      '"auth:login": never;',
      '"default:kept": never;',
      '"hello": never;',
    ]);
  });

  it("keeps a key that merely starts with the default namespace name", () => {
    const schema: ProjectSchema = {
      keys: { defaultish: { params: [] } },
    };

    expect(keyLinesOf(emitDeclarations(schema))).toEqual(['"defaultish": never;']);
  });

  it("rejects two keys that collide once the default namespace is stripped", () => {
    const schema: ProjectSchema = {
      keys: {
        "default:greeting:foo": { params: [] },
        "greeting:foo": { params: [] },
      },
    };

    expect(() => emitDeclarations(schema)).toThrow(
      "Translation key collision after stripping default namespace 'default': 'greeting:foo' maps to 'greeting:foo'",
    );
  });

  it("names the configured default namespace in the collision message", () => {
    const schema: ProjectSchema = {
      keys: {
        "common:hello": { params: [] },
        hello: { params: [] },
      },
    };

    expect(() => emitDeclarations(schema, { defaultNs: "common" })).toThrow(
      "Translation key collision after stripping default namespace 'common'",
    );
  });

  it("makes params required by default and optional under strictParams: false", () => {
    const schema: ProjectSchema = {
      keys: {
        "default:greeting": {
          params: [
            { name: "name", type: "string" },
            { name: "count", type: "number" },
          ],
        },
      },
    };

    expect(keyLinesOf(emitDeclarations(schema))).toEqual([
      '"greeting": { "name": string; "count": number };',
    ]);
    expect(keyLinesOf(emitDeclarations(schema, { strictParams: false }))).toEqual([
      '"greeting": { "name"?: string; "count"?: number };',
    ]);
  });

  it("rejects a param type it cannot express, naming key, param and type", () => {
    const schema: ProjectSchema = {
      keys: {
        "admin:greeting": {
          params: [{ name: "onDone", type: "() => void" as unknown as "string" }],
        },
      },
    };

    expect(() => emitDeclarations(schema)).toThrow(/admin:greeting.*onDone.*\(\) => void/);
  });

  it("accepts the two param types it can express", () => {
    const schema: ProjectSchema = {
      keys: {
        "admin:a": { params: [{ name: "name", type: "string" }] },
        "admin:b": { params: [{ name: "count", type: "number" }] },
      },
    };

    expect(keyLinesOf(emitDeclarations(schema))).toEqual([
      '"admin:a": { "name": string };',
      '"admin:b": { "count": number };',
    ]);
  });
});
